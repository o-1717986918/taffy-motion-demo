export const resolveAliases = <T extends string>(
  available: readonly string[],
  aliases: Record<T, readonly string[]>
): Record<T, string | null> => {
  const normalized = new Map(available.map((name) => [name.trim().toLocaleLowerCase(), name]));
  return Object.fromEntries(
    Object.entries<readonly string[]>(aliases).map(([semantic, candidates]) => [
      semantic,
      candidates.map((candidate) => normalized.get(candidate.trim().toLocaleLowerCase())).find(Boolean) ?? null
    ])
  ) as Record<T, string | null>;
};
